/* 云端扩展任务（th_prompts 表，后台可管理；未建表时为空） */
export async function cloudPromptTasks() {
  try {
    const { hasCloud, getSupabase } = await import('../supabase.js');
    if (!hasCloud()) return [];
    const sb = getSupabase();
    const { data, error } = await sb.from('th_prompts').select('*').eq('active', true).order('sort', { ascending: true });
    if (error || !data) return [];
    return data.map((r) => ({ id: 'c' + r.id, cat: r.category || '☁️ 云端任务', t: r.title, d: r.desc || '', p: r.prompt }));
  } catch (e) { return []; }
}